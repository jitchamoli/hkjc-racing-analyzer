#!/bin/bash
# Refresh tracking_data/backup/db_core_dump.sql.gz from the live DB and push if
# anything changed. Designed to run from launchd after each race day so the
# committed snapshot stays current.
#
# Behavior:
#   - No-op if the DB hasn't changed since last dump (gzip output is byte-stable
#     for identical content + same compression level, so git diff is the gate)
#   - No commit / no push if there's no diff
#   - All output appended to logs/auto_dump.log so you can audit catches/misses
#
# Manual run: bash scripts/auto_dump.sh

set -u

PROJECT_ROOT="/Users/jitendrachamoli/Documents/Project_Hub/hkjc_racing_analyzer"
LOG_DIR="$PROJECT_ROOT/logs"
LOG="$LOG_DIR/auto_dump.log"

mkdir -p "$LOG_DIR"

ts() { date '+%Y-%m-%d %H:%M:%S'; }

cd "$PROJECT_ROOT" || { echo "$(ts) FATAL: cannot cd to $PROJECT_ROOT" >> "$LOG"; exit 1; }

{
  echo ""
  echo "===== $(ts) auto_dump start ====="

  # Skip if DB doesn't exist or is empty (no point dumping nothing)
  if [ ! -s tracking_data/horse_history.db ]; then
    echo "$(ts) SKIP: DB missing or empty"
    exit 0
  fi

  # Generate the dump
  if ! python3 -m scripts.dump_db 2>&1; then
    echo "$(ts) FATAL: dump_db failed"
    exit 1
  fi

  # If nothing changed, exit cleanly without committing
  if git diff --quiet tracking_data/backup/db_core_dump.sql.gz; then
    echo "$(ts) NO-OP: dump unchanged since last commit"
    exit 0
  fi

  # Check we're on develop — refuse to commit on detached HEAD or unexpected branch
  branch=$(git symbolic-ref --short HEAD 2>/dev/null || echo "")
  if [ "$branch" != "develop" ] && [ "$branch" != "master" ]; then
    echo "$(ts) SKIP: on branch '$branch' — only auto-commit on develop/master"
    exit 0
  fi

  # Commit + push
  git add tracking_data/backup/db_core_dump.sql.gz
  msg="data: auto-refresh DB core dump $(date '+%Y-%m-%d')"
  git commit -m "$msg" -m "Auto-generated by scripts/auto_dump.sh after race-day DB changes."
  if git push origin "$branch" 2>&1; then
    echo "$(ts) OK: pushed $branch"
  else
    echo "$(ts) WARN: commit succeeded but push failed (network? auth?). Will retry next run."
  fi

  echo "===== $(ts) auto_dump done ====="
} >> "$LOG" 2>&1
